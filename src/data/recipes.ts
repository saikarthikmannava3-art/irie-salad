// === Helper Functions ===

export function getRecipeBySlug(slug: string): Recipe | undefined {
  return RECIPES.find((r) => r.slug === slug);
}

export function getActiveRecipes(): Recipe[] {
  return RECIPES.filter((r) => r.status === "active").sort((a, b) => a.sortOrder - b.sortOrder);
}

export function getRecipesByMealOccasion(occasion: MealOccasion): Recipe[] {
  return RECIPES.filter((r) => r.status === "active" && r.mealOccasion === occasion)
    .sort((a, b) => a.sortOrder - b.sortOrder);
}

export function getRecipesByRegion(region: IndianRegion): Recipe[] {
  return RECIPES.filter((r) => r.status === "active" && r.region === region)
    .sort((a, b) => a.sortOrder - b.sortOrder);
}

export function getRecipesByCookingMethod(method: CookingMethod): Recipe[] {
  return RECIPES.filter((r) => r.status === "active" && r.cookingMethod === method)
    .sort((a, b) => a.sortOrder - b.sortOrder);
}

